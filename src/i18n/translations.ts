export function t(lang: Language, key: string, params?: Record<string, string | number>): string {
  const selectedDict = TRANSLATIONS[lang] || TRANSLATIONS.EN;
  let text: string = (selectedDict as any)[key] ?? (TRANSLATIONS.EN as any)[key] ?? key;

  if (params) {
    for (const [k, v] of Object.entries(params)) {
      text = text.replace(new RegExp(`\\{${k}\\}`, 'g'), String(v));
    }
  }

  return text;
}

